#!/usr/bin/env node
// Batch-optimise project raster images to WebP with Sharp.
//
// Originals are never modified or deleted. Optimised files are written to a
// separate directory that mirrors the source tree, together with a JSON
// manifest (sources, outputs, dimensions, sizes, quality, status, references).
// Production references are NOT rewritten; see `--audit` for a migration map.
//
// Usage:
//   node scripts/optimize-images.mjs --audit        list and classify images + references (no encoding)
//   node scripts/optimize-images.mjs --dry-run      encode in memory and report results, write nothing
//   node scripts/optimize-images.mjs                optimise and write outputs + manifest
//   node scripts/optimize-images.mjs --verify       check outputs against the manifest
// Options:
//   --target=200 --max=250     size goal and hard limit in KB
//   --min-quality=62           lowest acceptable WebP quality (never goes below)
//   --max-quality=90           highest quality tried
//   --dirs=public              comma-separated directories to scan
//   --out=public/optimized     output directory (excluded from scanning)
//   --only=hero,kitchen        process only files whose path contains one of these strings
//   --force                    re-encode even when the source is unchanged

import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const args = Object.fromEntries(
  process.argv.slice(2).map((arg) => {
    const [key, value] = arg.replace(/^--/, "").split("=");
    return [key, value ?? true];
  }),
);
const config = {
  mode: args.verify ? "verify" : args.audit ? "audit" : args["dry-run"] ? "dry-run" : "optimize",
  targetKB: Number(args.target ?? 200),
  maxKB: Number(args.max ?? 250),
  minQuality: Number(args["min-quality"] ?? 62),
  maxQuality: Number(args["max-quality"] ?? 90),
  dirs: String(args.dirs ?? "public").split(",").map((dir) => dir.trim()).filter(Boolean),
  out: String(args.out ?? "public/optimized"),
  only: args.only ? String(args.only).split(",") : null,
  force: Boolean(args.force),
};
const OUT_DIR = path.resolve(ROOT, config.out);
const MANIFEST = path.join(OUT_DIR, "manifest.json");
const KB = 1024;

const RASTER = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif", ".tif", ".tiff", ".gif"]);
const SKIP_EXT = new Set([".svg", ".ico"]);
const IGNORED_DIRS = new Set(["node_modules", ".git", ".next", "out", "build", "dist", "coverage", ".vercel"]);
// Files that must keep their format or are generated by scripts/generate-brand-assets.mjs.
const SPECIAL = [
  { test: /(^|\/)(favicon|icon|apple-icon|opengraph-image|twitter-image)\.[a-z]+$/i, reason: "Next.js metadata file; must keep its format" },
  { test: /(^|\/)og-default\.jpe?g$/i, reason: "social preview image; JPEG is the most widely supported format for link previews" },
  { test: /(^|\/)logo-mark\.png$/i, reason: "logo for structured data and generated brand asset; keep PNG" },
];
const CODE_EXT = new Set([".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx", ".css", ".scss", ".json", ".md", ".mdx"]);
const toPosix = (file) => file.split(path.sep).join("/");
const fmtKB = (bytes) => `${(bytes / KB).toFixed(0)} KB`;

async function walk(dir, files = []) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return files;
  }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (IGNORED_DIRS.has(entry.name) || path.resolve(full) === OUT_DIR) continue;
      await walk(full, files);
    } else {
      files.push(full);
    }
  }
  return files;
}

const sha1 = (buffer) => createHash("sha1").update(buffer).digest("hex");
const optionsHash = sha1(Buffer.from(JSON.stringify([config.targetKB, config.maxKB, config.minQuality, config.maxQuality])));

/** Public URL for a file under public/ (null for files elsewhere). */
function publicUrl(file) {
  const rel = toPosix(path.relative(path.join(ROOT, "public"), file));
  return rel.startsWith("..") ? null : `/${rel}`;
}

/** Output path mirroring the source path relative to the project root. */
function outputPathFor(file) {
  const rel = path.relative(path.join(ROOT, "public"), file);
  const base = rel.startsWith("..") ? path.relative(ROOT, file) : rel;
  if (base.startsWith("..") || path.isAbsolute(base)) throw new Error(`${file} is outside the project; refusing to write outside ${config.out}`);
  return path.join(OUT_DIR, base).replace(/\.[^.]+$/, ".webp");
}

async function classify(file) {
  const rel = toPosix(path.relative(ROOT, file));
  const ext = path.extname(file).toLowerCase();
  if (SKIP_EXT.has(ext)) return { rel, status: "skipped-unsupported", reason: `${ext} is a vector/icon format; not converted` };
  if (!RASTER.has(ext)) return null;
  const special = SPECIAL.find((rule) => rule.test.test(rel));
  if (special) return { rel, status: "skipped-special", reason: special.reason };
  try {
    const meta = await sharp(file, { animated: true }).metadata();
    if ((meta.pages ?? 1) > 1) return { rel, status: "skipped-animated", reason: "animated image; not converted" };
    return { rel, status: "candidate", meta };
  } catch (error) {
    return { rel, status: "error", reason: `unreadable: ${error.message}` };
  }
}

/** Highest quality whose output fits `limitBytes`, by binary search over [min, max]. */
async function encodeWithin(pipelineFactory, limitBytes, minQ, maxQ) {
  let low = minQ;
  let high = maxQ;
  let best = null;
  while (low <= high) {
    const quality = Math.round((low + high) / 2);
    const buffer = await pipelineFactory(quality).toBuffer();
    if (buffer.length <= limitBytes) {
      best = { buffer, quality };
      low = quality + 1;
    } else {
      high = quality - 1;
    }
  }
  return best;
}

async function optimize(file, meta) {
  const hasAlpha = Boolean(meta.hasAlpha);
  // rotate() applies EXIF orientation so the stored pixels match how the image displays.
  // The quality search uses a faster effort level; the final encode uses the
  // slowest/best one, which produces an equal or smaller file at that quality.
  const pipeline = (quality, effort) =>
    sharp(file)
      .rotate()
      .webp({ quality, alphaQuality: hasAlpha ? 100 : quality, effort, smartSubsample: true });
  const fast = (quality) => pipeline(quality, 3);

  const target = config.targetKB * KB;
  const max = config.maxKB * KB;
  let result = await encodeWithin(fast, target, config.minQuality, config.maxQuality);
  let status = "optimized";
  if (!result) {
    result = await encodeWithin(fast, max, config.minQuality, config.maxQuality);
    status = "optimized-within-max";
  }
  if (!result) {
    // Even the quality floor exceeds the hard limit: keep the floor, flag for resizing.
    result = { quality: config.minQuality };
    status = "flagged-over-max";
  }
  result.buffer = await pipeline(result.quality, 6).toBuffer();
  const out = await sharp(result.buffer).metadata();
  return { ...result, status, width: out.width, height: out.height, hasAlpha: Boolean(out.hasAlpha) };
}

/** Find where each public image URL is referenced in source code. */
async function scanReferences(images) {
  const codeFiles = (await walk(path.join(ROOT, "src"))).concat(await walk(path.join(ROOT, "scripts")));
  const byUrl = new Map(images.filter((image) => image.url).map((image) => [image.url, []]));
  const missing = [];
  const dynamic = [];
  for (const file of codeFiles) {
    if (!CODE_EXT.has(path.extname(file).toLowerCase())) continue;
    const text = await readFile(file, "utf8");
    const rel = toPosix(path.relative(ROOT, file));
    for (const match of text.matchAll(/["'`(]((?:\/[\w.@-]+)+\.(?:jpe?g|png|webp|avif|gif|svg|ico))["'`)]/gi)) {
      const url = match[1];
      if (byUrl.has(url)) byUrl.get(url).push(rel);
      else if (!url.startsWith("/_next") && !(await exists(path.join(ROOT, "public", url)))) missing.push({ url, file: rel });
    }
    for (const match of text.matchAll(/`[^`]*\/images\/[^`]*\$\{[^`]*`/g)) dynamic.push({ file: rel, snippet: match[0].slice(0, 80) });
  }
  return { byUrl, missing, dynamic };
}

async function exists(file) {
  try {
    await stat(file);
    return true;
  } catch {
    return false;
  }
}

async function loadManifest() {
  try {
    return JSON.parse(await readFile(MANIFEST, "utf8"));
  } catch {
    return null;
  }
}

async function runOptimize() {
  const files = (await Promise.all(config.dirs.map((dir) => walk(path.resolve(ROOT, dir))))).flat().sort();
  const classified = (await Promise.all(files.map(classify))).filter(Boolean);
  const selected = config.only ? classified.filter((item) => config.only.some((part) => item.rel.includes(part))) : classified;
  const previous = (await loadManifest())?.images ?? [];
  const previousBySource = new Map(previous.map((entry) => [entry.source, entry]));
  const entries = [];
  const candidates = selected.filter((item) => item.status === "candidate");
  let index = 0;

  for (const item of selected) {
    const file = path.join(ROOT, item.rel);
    const url = publicUrl(file);
    const base = { source: item.rel, url };
    if (item.status !== "candidate") {
      entries.push({ ...base, status: item.status, reason: item.reason });
      continue;
    }
    index += 1;
    const sourceBuffer = await readFile(file);
    const sourceBytes = sourceBuffer.length;
    const hash = sha1(sourceBuffer);
    const outFile = outputPathFor(file);
    const outRel = toPosix(path.relative(ROOT, outFile));
    const prefix = `[${index}/${candidates.length}] ${item.rel}`;
    const meta = item.meta;
    const oriented = (meta.orientation ?? 1) >= 5 ? { width: meta.height, height: meta.width } : { width: meta.width, height: meta.height };
    const common = {
      ...base,
      sourceFormat: meta.format,
      sourceBytes,
      sourceHash: hash,
      width: oriented.width,
      height: oriented.height,
      hasAlpha: Boolean(meta.hasAlpha),
    };

    const prior = previousBySource.get(item.rel);
    if (!config.force && prior?.sourceHash === hash && prior.optionsHash === optionsHash && prior.output && (await exists(path.join(ROOT, prior.output)))) {
      console.log(`${prefix}  unchanged, skipped`);
      entries.push({ ...prior, unchanged: true });
      continue;
    }

    // Never re-encode WebP: each lossy pass would lower quality further.
    if (meta.format === "webp") {
      const withinMax = sourceBytes <= config.maxKB * KB;
      console.log(`${prefix}  already WebP (${fmtKB(sourceBytes)})${withinMax ? ", kept as is" : `, over ${config.maxKB} KB: reduce its pixel size instead`}`);
      entries.push({
        ...common,
        status: withinMax ? "skipped-already-optimal" : "flagged-webp-over-max",
        reason: withinMax ? `already WebP within ${config.maxKB} KB` : `already WebP; re-encoding would lose quality, resize it instead`,
      });
      continue;
    }

    try {
      const result = await optimize(file, meta);
      if (result.width !== oriented.width || result.height !== oriented.height) throw new Error("dimension mismatch after encoding");
      if (common.hasAlpha && !result.hasAlpha) throw new Error("transparency lost after encoding");
      const larger = result.buffer.length >= sourceBytes;
      const status = larger ? "skipped-no-gain" : result.status;
      if (!larger && config.mode === "optimize") {
        await mkdir(path.dirname(outFile), { recursive: true });
        await writeFile(outFile, result.buffer);
      }
      const saved = (((sourceBytes - result.buffer.length) / sourceBytes) * 100).toFixed(0);
      console.log(`${prefix}  ${fmtKB(sourceBytes)} -> ${fmtKB(result.buffer.length)} (q${result.quality}, -${saved}%) ${status}`);
      entries.push({
        ...common,
        status,
        output: larger ? null : outRel,
        outputUrl: larger ? null : publicUrl(outFile),
        outputFormat: "webp",
        outputBytes: result.buffer.length,
        quality: result.quality,
        optionsHash,
      });
    } catch (error) {
      console.error(`${prefix}  ERROR ${error.message}`);
      entries.push({ ...common, status: "error", reason: error.message });
    }
  }

  const refs = await scanReferences(entries);
  for (const entry of entries) entry.references = entry.url ? refs.byUrl.get(entry.url) ?? [] : [];

  const totals = summarize(entries);
  const manifest = {
    generated: new Date().toISOString(),
    settings: { targetKB: config.targetKB, maxKB: config.maxKB, minQuality: config.minQuality, maxQuality: config.maxQuality, dirs: config.dirs, out: config.out },
    totals,
    missingReferences: refs.missing,
    dynamicReferences: refs.dynamic,
    images: entries,
  };
  if (config.mode === "optimize") {
    // When --only is used, keep earlier entries for files that were not processed this run.
    const processed = new Set(entries.map((entry) => entry.source));
    manifest.images = [...previous.filter((entry) => !processed.has(entry.source)), ...entries].sort((a, b) => a.source.localeCompare(b.source));
    manifest.totals = summarize(manifest.images);
    await mkdir(OUT_DIR, { recursive: true });
    await writeFile(MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`);
  }
  report(manifest);
}

function summarize(entries) {
  const done = entries.filter((entry) => entry.output);
  const count = (status) => entries.filter((entry) => entry.status === status).length;
  return {
    scanned: entries.length,
    converted: done.length,
    sourceBytes: done.reduce((sum, entry) => sum + entry.sourceBytes, 0),
    outputBytes: done.reduce((sum, entry) => sum + entry.outputBytes, 0),
    withinTarget: count("optimized"),
    withinMax: count("optimized-within-max"),
    flaggedOverMax: count("flagged-over-max"),
    skipped: entries.filter((entry) => entry.status.startsWith("skipped")).length,
    errors: count("error"),
  };
}

function report(manifest) {
  const t = manifest.totals;
  console.log(`\n${config.mode.toUpperCase()} SUMMARY`);
  console.log(`  converted: ${t.converted}  (${fmtKB(t.sourceBytes)} -> ${fmtKB(t.outputBytes)})`);
  console.log(`  <= ${config.targetKB} KB: ${t.withinTarget}   <= ${config.maxKB} KB: ${t.withinMax}   flagged over ${config.maxKB} KB: ${t.flaggedOverMax}   skipped: ${t.skipped}   errors: ${t.errors}`);
  for (const entry of manifest.images.filter((item) => item.status.startsWith("flagged") || item.status === "error")) {
    console.log(`  ! ${entry.source}: ${entry.status} ${entry.reason ?? fmtKB(entry.outputBytes)}`);
  }
  for (const entry of manifest.images.filter((item) => item.status.startsWith("skipped") && item.status !== "skipped-already-optimal")) {
    console.log(`  - ${entry.source}: ${entry.reason ?? entry.status}`);
  }
  if (manifest.missingReferences.length) console.log(`  missing references: ${JSON.stringify(manifest.missingReferences)}`);
  if (manifest.dynamicReferences.length) console.log(`  dynamic references to review: ${manifest.dynamicReferences.length}`);
  if (config.mode === "optimize") console.log(`  manifest: ${toPosix(path.relative(ROOT, MANIFEST))}`);
}

async function runAudit() {
  const files = (await Promise.all(config.dirs.map((dir) => walk(path.resolve(ROOT, dir))))).flat().sort();
  const classified = (await Promise.all(files.map(classify))).filter(Boolean);
  const entries = await Promise.all(
    classified.map(async (item) => {
      const file = path.join(ROOT, item.rel);
      const bytes = (await stat(file)).size;
      return { ...item, url: publicUrl(file), bytes, overTarget: bytes > config.targetKB * KB };
    }),
  );
  const refs = await scanReferences(entries);
  console.log(`AUDIT: ${entries.length} image files in ${config.dirs.join(", ")}\n`);
  for (const entry of entries) {
    const used = entry.url ? refs.byUrl.get(entry.url) ?? [] : [];
    const action = entry.status === "candidate" ? (entry.overTarget ? "convert" : "convert (small)") : entry.status;
    const migrate = entry.status === "candidate" && entry.url ? ` -> ${publicUrl(outputPathFor(path.join(ROOT, entry.rel)))}` : "";
    console.log(`${fmtKB(entry.bytes).padStart(7)}  ${action.padEnd(20)} ${entry.rel}${migrate}`);
    console.log(`         refs: ${used.length ? used.join(", ") : entry.url ? "none found (unused or referenced dynamically)" : "n/a"}${entry.reason ? `  | ${entry.reason}` : ""}`);
  }
  if (refs.missing.length) console.log(`\nMissing references (path not found under public/):\n${refs.missing.map((m) => `  ${m.url} in ${m.file}`).join("\n")}`);
  if (refs.dynamic.length) console.log(`\nDynamic references to review manually:\n${refs.dynamic.map((d) => `  ${d.file}: ${d.snippet}`).join("\n")}`);
}

async function runVerify() {
  const manifest = await loadManifest();
  if (!manifest) {
    console.error(`No manifest at ${toPosix(path.relative(ROOT, MANIFEST))}. Run the optimiser first.`);
    process.exit(1);
  }
  const problems = [];
  for (const entry of manifest.images.filter((item) => item.output)) {
    const source = path.join(ROOT, entry.source);
    const output = path.join(ROOT, entry.output);
    if (!(await exists(source))) problems.push(`${entry.source}: original missing`);
    if (!(await exists(output))) {
      problems.push(`${entry.output}: output missing`);
      continue;
    }
    const buffer = await readFile(output);
    if (sha1(await readFile(source)) !== entry.sourceHash) problems.push(`${entry.source}: original changed since optimisation (re-run optimiser)`);
    try {
      const meta = await sharp(buffer).metadata();
      await sharp(buffer).stats(); // full decode
      if (meta.format !== "webp") problems.push(`${entry.output}: not WebP`);
      if (meta.width !== entry.width || meta.height !== entry.height) problems.push(`${entry.output}: ${meta.width}x${meta.height}, expected ${entry.width}x${entry.height}`);
      if (entry.hasAlpha && !meta.hasAlpha) problems.push(`${entry.output}: transparency lost`);
      if (buffer.length > manifest.settings.maxKB * KB && entry.status !== "flagged-over-max") problems.push(`${entry.output}: ${fmtKB(buffer.length)} exceeds ${manifest.settings.maxKB} KB`);
    } catch (error) {
      problems.push(`${entry.output}: cannot decode (${error.message})`);
    }
  }
  for (const missing of manifest.missingReferences ?? []) problems.push(`missing reference ${missing.url} in ${missing.file}`);
  const flagged = manifest.images.filter((item) => item.status === "flagged-over-max").map((item) => item.source);
  console.log(`VERIFY: ${manifest.images.filter((item) => item.output).length} outputs checked`);
  if (flagged.length) console.log(`  flagged (over ${manifest.settings.maxKB} KB at quality floor): ${flagged.join(", ")}`);
  if (problems.length) {
    console.error(`  ${problems.length} problem(s):\n  ${problems.join("\n  ")}`);
    process.exit(1);
  }
  console.log("  all outputs present, decodable, WebP, same dimensions, transparency preserved, within limits");
}

const run = { audit: runAudit, verify: runVerify, "dry-run": runOptimize, optimize: runOptimize }[config.mode];
run().catch((error) => {
  console.error(error);
  process.exit(1);
});
